"""Tests for ReportLab PDF health summary generation and report endpoints."""

from datetime import datetime, timezone
from unittest.mock import patch

from fastapi.testclient import TestClient

from app.services.report_service import (
    REPORT_FOOTER_TEXT,
    REPORT_HEADER_TEXT,
    ReportService,
)
from tests.conftest import TEST_USER_ID


class TestPDFGeneration:
    def test_builds_valid_pdf_with_disclaimers_and_data(self) -> None:
        service = ReportService()
        pdf_bytes = service.build_pdf_bytes(
            user_profile={
                "display_name": "Rohan Sharma",
                "date_of_birth": "1992-06-15",
                "gender": "male",
                "medical_conditions": ["Seasonal Allergic Rhinitis"],
                "allergies": ["Dust mites"],
            },
            conversations=[
                {
                    "id": "conv-1",
                    "title": "Seasonal cough inquiry",
                    "created_at": "2026-11-10T10:00:00Z",
                    "messages": [
                        {"role": "user", "content": "I have a mild dry cough for 3 days."},
                        {
                            "role": "assistant",
                            "content": "A mild dry cough may be related to allergies or viral irritation.",
                        },
                    ],
                }
            ],
            health_records=[
                {
                    "record_type": "vital_signs",
                    "recorded_at": "2026-11-10T09:00:00Z",
                    "source": "user_entered",
                    "data": {"blood_pressure": "120/78", "heart_rate": 72, "temperature_f": 98.4},
                },
                {
                    "record_type": "symptom",
                    "recorded_at": "2026-11-10T09:30:00Z",
                    "source": "user_entered",
                    "data": {"symptom": "Dry cough", "severity": "mild"},
                },
            ],
            ai_observations=[
                "Symptoms mentioned across selected conversations: cough.",
                "2 logged health record(s) included for clinician review.",
            ],
            date_range={"start_date": "2026-11-01", "end_date": "2026-11-18"},
        )

        assert isinstance(pdf_bytes, bytes)
        assert len(pdf_bytes) > 1000
        # Valid PDF magic header and EOF trailer
        assert pdf_bytes.startswith(b"%PDF-")
        assert b"%%EOF" in pdf_bytes[-128:]

    def test_header_and_footer_constants_match_requirements(self) -> None:
        assert REPORT_HEADER_TEXT == "AI Health Information Summary — NOT a Medical Document"
        assert REPORT_FOOTER_TEXT == "Generated by AI Health Monitor. This is not a medical diagnosis."


class TestReportEndpoints:
    def test_generate_and_download_report(self, authed_client: TestClient) -> None:
        now = datetime.now(timezone.utc).isoformat()
        sample_pdf = ReportService().build_pdf_bytes(
            user_profile={"display_name": "Test Patient"},
            health_records=[],
            conversations=[],
        )
        report_row = {
            "id": "rep-123",
            "user_id": TEST_USER_ID,
            "report_type": "health_summary",
            "content": {"title": REPORT_HEADER_TEXT},
            "pdf_path": f"{TEST_USER_ID}/report_abc.pdf",
            "download_url": "https://storage.example.com/report_abc.pdf",
            "generated_at": now,
        }

        with patch(
            "app.routers.reports.report_service.generate_and_store_report",
            return_value=report_row,
        ):
            gen_resp = authed_client.post(
                "/api/reports/generate",
                json={
                    "conversation_ids": [],
                    "include_vitals": True,
                    "date_range": {"start_date": "2026-11-01", "end_date": "2026-11-18"},
                },
            )

        assert gen_resp.status_code == 201
        assert gen_resp.json()["id"] == "rep-123"

        with (
            patch(
                "app.routers.reports.supabase_service.get_health_report",
                return_value=report_row,
            ),
            patch(
                "app.routers.reports.supabase_service.download_file",
                return_value=sample_pdf,
            ),
        ):
            dl_resp = authed_client.get("/api/reports/rep-123/download")

        assert dl_resp.status_code == 200
        assert dl_resp.headers["content-type"] == "application/pdf"
        assert dl_resp.content.startswith(b"%PDF-")

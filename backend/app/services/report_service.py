"""PDF Health Information Summary generator using ReportLab."""

import io
import logging
import uuid
from datetime import date, datetime, timezone
from typing import Any, Optional
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.config import settings
from app.services.supabase_service import SupabaseService, supabase_service as default_supabase
from app.utils.safety import MEDICAL_DISCLAIMER

logger = logging.getLogger(__name__)

REPORT_HEADER_TEXT = "AI Health Information Summary — NOT a Medical Document"
REPORT_FOOTER_TEXT = "Generated by AI Health Monitor. This is not a medical diagnosis."


class ReportService:
    """Generates structured PDF health summaries and persists them to Supabase Storage."""

    def __init__(self, supabase_service: Optional[SupabaseService] = None) -> None:
        self._supabase = supabase_service or default_supabase

    @staticmethod
    def _draw_header_footer(canvas: Any, doc: Any) -> None:
        """Draw mandatory non-medical disclaimer header and footer on every PDF page."""
        canvas.saveState()
        page_width, page_height = A4

        # Header bar
        canvas.setStrokeColor(colors.HexColor("#2563EB"))
        canvas.setLineWidth(0.75)
        canvas.line(18 * mm, page_height - 16 * mm, page_width - 18 * mm, page_height - 16 * mm)

        canvas.setFont("Helvetica-Bold", 9)
        canvas.setFillColor(colors.HexColor("#1E3A8A"))
        canvas.drawString(18 * mm, page_height - 13 * mm, REPORT_HEADER_TEXT)

        # Footer bar
        canvas.setStrokeColor(colors.HexColor("#CBD5E1"))
        canvas.setLineWidth(0.5)
        canvas.line(18 * mm, 16 * mm, page_width - 18 * mm, 16 * mm)

        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#475569"))
        canvas.drawString(18 * mm, 11 * mm, REPORT_FOOTER_TEXT)
        canvas.drawRightString(page_width - 18 * mm, 11 * mm, f"Page {doc.page}")

        canvas.restoreState()

    @staticmethod
    def _safe_para(text: Any) -> str:
        """Escape XML special characters for safe ReportLab Paragraph rendering."""
        return escape(str(text or "")).replace("\n", "<br/>")

    def build_pdf_bytes(
        self,
        user_profile: Optional[dict[str, Any]] = None,
        conversations: Optional[list[dict[str, Any]]] = None,
        health_records: Optional[list[dict[str, Any]]] = None,
        ai_observations: Optional[list[str]] = None,
        date_range: Optional[dict[str, Optional[str]]] = None,
    ) -> bytes:
        """Render a complete ReportLab PDF in memory and return its bytes."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=18 * mm,
            rightMargin=18 * mm,
            topMargin=22 * mm,
            bottomMargin=22 * mm,
            title=REPORT_HEADER_TEXT,
            author="AI Health Monitor",
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "ReportTitle",
            parent=styles["Heading1"],
            fontSize=16,
            textColor=colors.HexColor("#1E3A8A"),
            spaceAfter=6,
        )
        heading_style = ParagraphStyle(
            "SectionHeading",
            parent=styles["Heading2"],
            fontSize=12,
            textColor=colors.HexColor("#0F766E"),
            spaceBefore=12,
            spaceAfter=6,
        )
        body_style = ParagraphStyle(
            "BodyTextCustom",
            parent=styles["BodyText"],
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#1E293B"),
        )
        disclaimer_style = ParagraphStyle(
            "DisclaimerBox",
            parent=styles["BodyText"],
            fontSize=8.5,
            leading=12,
            textColor=colors.HexColor("#7F1D1D"),
            backColor=colors.HexColor("#FEF2F2"),
            borderColor=colors.HexColor("#FCA5A5"),
            borderWidth=0.75,
            borderPadding=8,
        )

        story: list[Any] = []
        generated_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

        story.append(Paragraph(self._safe_para(REPORT_HEADER_TEXT), title_style))
        story.append(Paragraph(f"Generated on: {self._safe_para(generated_str)}", body_style))

        if date_range and (date_range.get("start_date") or date_range.get("end_date")):
            start_s = date_range.get("start_date") or "Beginning"
            end_s = date_range.get("end_date") or "Present"
            story.append(
                Paragraph(
                    f"Date Range: {self._safe_para(start_s)} to {self._safe_para(end_s)}",
                    body_style,
                )
            )

        story.append(Spacer(1, 6))
        story.append(Paragraph(self._safe_para(MEDICAL_DISCLAIMER), disclaimer_style))
        story.append(Spacer(1, 8))

        # 1. User Profile Overview
        story.append(Paragraph("1. User Profile Overview", heading_style))
        profile = user_profile or {}
        profile_rows = [
            ["Field", "Details"],
            ["Display Name", str(profile.get("display_name") or "Not specified")],
            ["Date of Birth", str(profile.get("date_of_birth") or "Not specified")],
            ["Gender", str(profile.get("gender") or "Not specified")],
            [
                "Self-Reported Conditions",
                ", ".join(profile.get("medical_conditions") or []) or "None listed",
            ],
            [
                "Self-Reported Allergies",
                ", ".join(profile.get("allergies") or []) or "None listed",
            ],
        ]
        profile_table = Table(
            [
                [Paragraph(f"<b>{self._safe_para(c)}</b>", body_style) for c in profile_rows[0]]
            ]
            + [
                [Paragraph(self._safe_para(r[0]), body_style), Paragraph(self._safe_para(r[1]), body_style)]
                for r in profile_rows[1:]
            ],
            colWidths=[50 * mm, 124 * mm],
        )
        profile_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EFF6FF")),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("PADDING", (0, 0), (-1, -1), 5),
                ]
            )
        )
        story.append(profile_table)
        story.append(Spacer(1, 8))

        # 2. Vital Signs & Logged Health Records (including symptoms)
        records = health_records or []
        vitals = [r for r in records if r.get("record_type") == "vital_signs"]
        symptoms = [r for r in records if r.get("record_type") == "symptom"]
        other_records = [
            r for r in records if r.get("record_type") not in ("vital_signs", "symptom")
        ]

        story.append(Paragraph("2. Vital Signs", heading_style))
        if vitals:
            vital_rows = [["Recorded At", "Measurements", "Source"]]
            for rec in vitals[:25]:
                data = rec.get("data") or {}
                formatted = ", ".join(f"{k}: {v}" for k, v in data.items())
                vital_rows.append(
                    [
                        str(rec.get("recorded_at", ""))[:19],
                        formatted or "No values",
                        str(rec.get("source", "user_entered")),
                    ]
                )
            story.append(self._make_styled_table(vital_rows, [38 * mm, 102 * mm, 34 * mm], body_style))
        else:
            story.append(Paragraph("No vital signs records included in this report.", body_style))

        story.append(Paragraph("3. Logged Symptoms & Health Notes", heading_style))
        combined_notes = symptoms + other_records
        if combined_notes:
            note_rows = [["Recorded At", "Type", "Details"]]
            for rec in combined_notes[:30]:
                data = rec.get("data") or {}
                formatted = ", ".join(f"{k}: {v}" for k, v in data.items())
                note_rows.append(
                    [
                        str(rec.get("recorded_at", ""))[:19],
                        str(rec.get("record_type", "note")),
                        formatted or "No details",
                    ]
                )
            story.append(self._make_styled_table(note_rows, [38 * mm, 32 * mm, 104 * mm], body_style))
        else:
            story.append(Paragraph("No symptom or health records included in this report.", body_style))

        # 4. Conversation Summaries
        story.append(Paragraph("4. Conversation Summaries", heading_style))
        convs = conversations or []
        if convs:
            for idx, conv in enumerate(convs[:20], start=1):
                title = conv.get("title") or f"Conversation {idx}"
                created = str(conv.get("created_at", ""))[:19]
                story.append(
                    Paragraph(
                        f"<b>{idx}. {self._safe_para(title)}</b> ({self._safe_para(created)})",
                        body_style,
                    )
                )
                msgs = conv.get("messages") or []
                if msgs:
                    for msg in msgs[:10]:
                        role = str(msg.get("role", "user")).capitalize()
                        snippet = str(msg.get("content", ""))
                        if len(snippet) > 450:
                            snippet = snippet[:447] + "..."
                        story.append(
                            Paragraph(
                                f"<b>{self._safe_para(role)}:</b> {self._safe_para(snippet)}",
                                body_style,
                            )
                        )
                else:
                    story.append(Paragraph("No messages recorded in this conversation.", body_style))
                story.append(Spacer(1, 5))
        else:
            story.append(Paragraph("No conversations were selected for this report.", body_style))

        # 5. AI Observations (Non-Diagnostic)
        story.append(Paragraph("5. AI Observations (Non-Diagnostic)", heading_style))
        observations = ai_observations or []
        if observations:
            for obs in observations[:15]:
                story.append(Paragraph(f"&bull; {self._safe_para(obs)}", body_style))
        else:
            story.append(
                Paragraph(
                    "Bring this summary to your next healthcare appointment to help discuss "
                    "your symptom timeline and self-tracked vital signs with a qualified clinician.",
                    body_style,
                )
            )

        doc.build(
            story,
            onFirstPage=self._draw_header_footer,
            onLaterPages=self._draw_header_footer,
        )
        return buffer.getvalue()

    def _make_styled_table(
        self,
        rows: list[list[str]],
        col_widths: list[float],
        body_style: ParagraphStyle,
    ) -> Table:
        table_data = [
            [Paragraph(f"<b>{self._safe_para(cell)}</b>", body_style) for cell in rows[0]]
        ] + [
            [Paragraph(self._safe_para(cell), body_style) for cell in row]
            for row in rows[1:]
        ]
        table = Table(table_data, colWidths=col_widths, repeatRows=1)
        table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F0FDFA")),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("PADDING", (0, 0), (-1, -1), 5),
                ]
            )
        )
        return table

    @staticmethod
    def _in_date_range(
        timestamp_value: Any,
        start_date: Optional[date],
        end_date: Optional[date],
    ) -> bool:
        if not start_date and not end_date:
            return True
        if not timestamp_value:
            return True
        try:
            dt = date.fromisoformat(str(timestamp_value)[:10])
        except ValueError:
            return True
        if start_date and dt < start_date:
            return False
        if end_date and dt > end_date:
            return False
        return True

    def generate_and_store_report(
        self,
        user_id: str,
        conversation_ids: list[str],
        include_vitals: bool = True,
        start_date: Optional[date] = None,
        end_date: Optional[date] = None,
        report_type: str = "health_summary",
    ) -> dict[str, Any]:
        """Gather user data, render PDF, upload to Supabase Storage, and create DB record."""
        profile = self._supabase.get_user_profile(user_id)

        # Fetch selected conversations (or recent active ones if none explicitly chosen)
        selected_conversations: list[dict[str, Any]] = []
        if conversation_ids:
            for conv_id in conversation_ids:
                conv = self._supabase.get_conversation(user_id, conv_id)
                if conv and self._in_date_range(conv.get("created_at"), start_date, end_date):
                    msgs = self._supabase.get_conversation_messages(user_id, conv_id)
                    selected_conversations.append({**conv, "messages": msgs})
        else:
            convs, _ = self._supabase.list_conversations(user_id, page=1, page_size=10)
            for conv in convs:
                if self._in_date_range(conv.get("created_at"), start_date, end_date):
                    msgs = self._supabase.get_conversation_messages(user_id, conv["id"])
                    selected_conversations.append({**conv, "messages": msgs})

        # Fetch health records
        all_records = self._supabase.list_health_records(user_id, limit=200)
        filtered_records = [
            rec
            for rec in all_records
            if self._in_date_range(rec.get("recorded_at"), start_date, end_date)
            and (include_vitals or rec.get("record_type") != "vital_signs")
        ]

        # Extract detected symptoms & key AI observations from conversation metadata
        observations: list[str] = []
        detected_symptoms: set[str] = set()
        for conv in selected_conversations:
            for msg in conv.get("messages") or []:
                meta = msg.get("metadata") or {}
                if isinstance(meta, dict):
                    for sym in meta.get("detected_symptoms") or []:
                        detected_symptoms.add(str(sym))
                    if meta.get("is_emergency"):
                        observations.append(
                            f"Emergency warning was triggered in conversation '{conv.get('title', 'Chat')}' "
                            f"(category: {meta.get('emergency_category', 'general')})."
                        )

        if detected_symptoms:
            observations.insert(
                0,
                f"Symptoms mentioned across selected conversations: {', '.join(sorted(detected_symptoms))}.",
            )
        if filtered_records:
            observations.append(
                f"{len(filtered_records)} logged health record(s) included for clinician review."
            )

        date_range_dict = {
            "start_date": start_date.isoformat() if start_date else None,
            "end_date": end_date.isoformat() if end_date else None,
        }

        pdf_bytes = self.build_pdf_bytes(
            user_profile=profile,
            conversations=selected_conversations,
            health_records=filtered_records,
            ai_observations=observations,
            date_range=date_range_dict,
        )

        storage_path = f"{user_id}/report_{uuid.uuid4().hex}.pdf"
        download_url = self._supabase.upload_file(
            bucket=settings.SUPABASE_REPORTS_BUCKET,
            storage_path=storage_path,
            file_bytes=pdf_bytes,
            content_type="application/pdf",
        )

        content_summary = {
            "title": REPORT_HEADER_TEXT,
            "conversation_count": len(selected_conversations),
            "record_count": len(filtered_records),
            "include_vitals": include_vitals,
            "date_range": date_range_dict,
            "detected_symptoms": sorted(detected_symptoms),
            "observations": observations,
            "disclaimer": MEDICAL_DISCLAIMER,
        }

        report_row = self._supabase.create_health_report(
            user_id=user_id,
            report_type=report_type,
            content=content_summary,
            pdf_path=storage_path,
        )

        return {**report_row, "download_url": download_url}


report_service = ReportService()
